import { basename } from "node:path";
import type { BuildResult } from "./KnowledgeGraphBuilder.js";

/** Markdown report written next to graph.json. Uses only relative paths. */
export function buildGraphReport(result: BuildResult, rootDir: string): string {
  const { graph, snapshot } = result;
  const counts = graph.countByKind();
  const degree = new Map<string, number>();
  for (const edge of graph.edges()) {
    degree.set(edge.source, (degree.get(edge.source) ?? 0) + 1);
    degree.set(edge.target, (degree.get(edge.target) ?? 0) + 1);
  }
  const central = [...degree.entries()]
    .sort((a, b) => b[1] - a[1])
    .slice(0, 10)
    .map(([id, connections]) => ({ node: graph.getNode(id), connections }))
    .filter((x): x is { node: NonNullable<typeof x.node>; connections: number } => x.node !== null);

  const lines = [
    "# GRAPH_REPORT.md",
    "",
    "> Auto-generated by `bun run build:graph`. Use it before asking about architecture.",
    "",
    "## Build Summary",
    "",
    "| Metric | Value |",
    "|--------|-------|",
    `| Root directory | \`${snapshot.metadata.rootDir}\` |`,
    `| Files processed | ${result.filesProcessed} |`,
    `| Files skipped | ${result.filesSkipped} |`,
    `| Nodes created | ${result.nodesCreated} |`,
    `| Edges created | ${result.edgesCreated} |`,
    `| Build time | ${result.durationMs}ms |`,
    `| Generated | ${snapshot.metadata.builtAt} |`,
    "",
    "## Node Types",
    "",
    ...Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([kind, n]) => `- **${kind}**: ${n}`),
    "",
    "## Languages",
    "",
    ...Object.entries(result.byLanguage).sort((a, b) => b[1] - a[1]).map(([lang, n]) => `- **${lang}**: ${n} files`),
    "",
    "## High-Connectivity Nodes (Architectural Core)",
    "",
    "| Node | Kind | Connections |",
    "|------|------|-------------|",
    ...central.map(({ node, connections }) => `| \`${node.name}\` | ${node.kind} | ${connections} |`),
    "",
    "## Agent Usage Instructions",
    "",
    "1. Use `GraphifyQuery` with op=`central` to find high-importance nodes.",
    "2. Use op=`search` to find specific files/classes.",
    "3. Use op=`neighbors` / op=`path` to explore connections.",
    "4. Prefer graph traversal over raw `Glob`/`Grep` for structural questions.",
    "",
    `Built from \`${basename(rootDir)}\` (only the directory name is stored in graph.json).`,
    "",
  ];
  return lines.join("\n");
}
